#!/usr/bin/env python
"""
合并 manga (roboflow) + western comic (dataset/bubble) 训练数据。

输出: dataset/mixed_bubble/
  - images/train, images/val, images/test
  - labels/train, labels/val, labels/test
  - dataset.yaml

所有标签统一为单类 0: speech-bubble（region type 交给 RegionClassifier 处理）。
"""

import shutil
from pathlib import Path


def normalize_label(src: Path, dst: Path) -> None:
    """将标签统一为 class 0，保持 polygon 坐标。"""
    lines = []
    for line in src.read_text(encoding="utf-8").strip().splitlines():
        parts = line.strip().split()
        if not parts:
            continue
        # class_id 统一为 0
        parts[0] = "0"
        lines.append(" ".join(parts))
    if lines:
        dst.write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_split(src_img_dir: Path, src_lbl_dir: Path, dst_img_dir: Path, dst_lbl_dir: Path) -> int:
    count = 0
    dst_img_dir.mkdir(parents=True, exist_ok=True)
    dst_lbl_dir.mkdir(parents=True, exist_ok=True)
    for img_path in sorted(src_img_dir.iterdir()):
        if img_path.suffix.lower() not in (".png", ".jpg", ".jpeg"):
            continue
        lbl_path = src_lbl_dir / f"{img_path.stem}.txt"
        if not lbl_path.exists():
            continue
        dst_img = dst_img_dir / img_path.name
        dst_lbl = dst_lbl_dir / f"{img_path.stem}.txt"
        shutil.copy2(img_path, dst_img)
        normalize_label(lbl_path, dst_lbl)
        count += 1
    return count


def main() -> None:
    root = Path("G:/trainslate")
    out_dir = root / "dataset" / "mixed_bubble"

    # 清空旧数据
    if out_dir.exists():
        shutil.rmtree(out_dir)

    splits = {
        "train": ("train", "train"),
        "val": ("valid", "val"),
        "test": ("test", "test"),
    }

    stats = {}

    # 1. 复制 manga (roboflow)
    for dst_split, (src_split, _) in splits.items():
        src_img = root / "dataset" / "roboflow" / src_split / "images"
        src_lbl = root / "dataset" / "roboflow" / src_split / "labels"
        dst_img = out_dir / "images" / dst_split
        dst_lbl = out_dir / "labels" / dst_split
        n = copy_split(src_img, src_lbl, dst_img, dst_lbl)
        stats[f"manga_{dst_split}"] = n

    # 2. 复制 western comic (dataset/bubble)
    western_splits = {
        "train": ("train", "train"),
        "val": ("val", "val"),
    }
    for dst_split, (src_split, _) in western_splits.items():
        src_img = root / "dataset" / "bubble" / "images" / src_split
        src_lbl = root / "dataset" / "bubble" / "labels" / src_split
        dst_img = out_dir / "images" / dst_split
        dst_lbl = out_dir / "labels" / dst_split
        n = copy_split(src_img, src_lbl, dst_img, dst_lbl)
        stats[f"western_{dst_split}"] = n

    # 3. 写 dataset.yaml
    yaml_path = out_dir / "dataset.yaml"
    yaml_path.write_text(
        "# Mixed Manga + Western Comic Bubble Dataset\n"
        "# Auto-generated by scripts/merge_bubble_datasets.py\n\n"
        f"path: {out_dir.relative_to(root).as_posix()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n\n"
        "nc: 1\n"
        "names:\n"
        "  0: speech-bubble\n",
        encoding="utf-8",
    )

    # 汇总
    total_train = stats.get("manga_train", 0) + stats.get("western_train", 0)
    total_val = stats.get("manga_val", 0) + stats.get("western_val", 0)
    print(f"Merged dataset at: {out_dir}")
    print(f"  manga train={stats.get('manga_train', 0)}, val={stats.get('manga_val', 0)}, test={stats.get('manga_test', 0)}")
    print(f"  western train={stats.get('western_train', 0)}, val={stats.get('western_val', 0)}")
    print(f"  total train={total_train}, val={total_val}, test={stats.get('manga_test', 0)}")


if __name__ == "__main__":
    main()
